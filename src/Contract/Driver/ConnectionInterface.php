<?php

declare(strict_types=1);

namespace G\Orm\Contract\Driver;

use G\Orm\Compiler\Platform\PlatformInterface;

/**
 * Wraps an open database session.
 *
 * Exposes explicit transaction control, value/identifier quoting, statement
 * preparation and the SQL platform (dialect) of the engine behind the
 * session. Transaction control is deliberately explicit: the connection
 * never opens or commits transactions on its own.
 */
interface ConnectionInterface
{
    /**
     * The SQL platform (dialect) of the engine this session is connected to.
     *
     * Resolved once at connection time; consumers (the compiler above all)
     * delegate every dialect-sensitive SQL fragment to it.
     */
    public function getPlatform(): PlatformInterface;

    /**
     * Begin a transaction.
     *
     * @throws \G\Orm\Exception\TransactionException
     */
    public function beginTransaction(): void;

    /**
     * Commit the active transaction.
     *
     * @throws \G\Orm\Exception\TransactionException
     */
    public function commit(): void;

    /**
     * Roll back the active transaction.
     *
     * @throws \G\Orm\Exception\TransactionException
     */
    public function rollBack(): void;

    /**
     * Whether a transaction is currently active on this connection.
     */
    public function inTransaction(): bool;

    /**
     * The identifier generated by the last INSERT on this session.
     *
     * The last inserted id is state owned by the database session, not by an
     * individual statement result. For tables with a composite primary key
     * (no single auto-generated column) this returns 0, or throws, depending
     * on the engine — standard behaviour; callers must rely on extracted key
     * values instead.
     *
     * @param string|null $name Optional sequence name (e.g. PostgreSQL).
     *
     * @throws \G\Orm\Exception\DriverException
     */
    public function lastInsertId(?string $name = null): string|int;

    /**
     * Quote a literal value for safe inclusion in SQL.
     *
     * Prepared statements remain the preferred mechanism; this exists for
     * the cases where a literal must be inlined.
     */
    public function quote(string $value): string;

    /**
     * Quote an identifier (table or column name) for the active engine.
     */
    public function quoteIdentifier(string $identifier): string;

    /**
     * Prepare an SQL statement for execution.
     *
     * @throws \G\Orm\Exception\QueryException When the statement cannot be prepared.
     */
    public function prepare(string $sql): StatementInterface;
}
